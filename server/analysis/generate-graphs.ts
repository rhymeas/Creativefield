// Regenerates server/analysis/generated/graph-templates.ts from the pinned blueprints.
// Usage: npx tsx server/analysis/generate-graphs.ts
import {readFileSync, mkdirSync, writeFileSync} from "node:fs";
import {join} from "node:path";
import {fileURLToPath} from "node:url";
import {generateTemplates, BLUEPRINT_DIR} from "./blueprint-conversion";

const HERE = fileURLToPath(new URL(".", import.meta.url));
const OUT_DIR = join(HERE, "generated");

type Provenance = {blueprints: Record<"moge" | "sam3", {sha256: string; file: string}>};
const provenance = JSON.parse(readFileSync(join(BLUEPRINT_DIR, "provenance.json"), "utf8")) as Provenance;
const templates = generateTemplates();

const literal = (value: unknown): string => JSON.stringify(value, null, 2);

const source = `/*
 * GENERATED FILE - do not edit by hand.
 *
 * Generated by: npx tsx server/analysis/generate-graphs.ts
 * From the byte-identical official blueprints pinned in ../../analysis/blueprints:
 *   Geometry Estimation (MoGe).json  sha256 ${provenance.blueprints.moge.sha256}
 *   Video Segmentation (SAM3).json   sha256 ${provenance.blueprints.sam3.sha256}
 *
 * CORE is the blueprint graph converted by src/workflow/ui-to-api.ts (subgraph
 * expanded, editor node replacement applied, source loader + widget proxies set).
 * APPENDED are the only nodes this project adds to the blueprint: SaveGLB for the
 * MoGe mesh and MaskToImage -> SaveImage for the SAM 3.1 person masks.
 * test/analysis-blueprints.test.ts proves CORE still equals the conversion.
 */
import type {ApiGraph} from "../../../src/workflow/build";

/** An API prompt node graph; _meta is the editor title and is ignored when running. */
export type BlueprintGraph = Record<string, {class_type: string; inputs: Record<string, unknown>; _meta?: {title?: string}}>;

export const MOGE_BLUEPRINT_SHA256 = ${JSON.stringify(provenance.blueprints.moge.sha256)};
export const SAM3_BLUEPRINT_SHA256 = ${JSON.stringify(provenance.blueprints.sam3.sha256)};

export const MOGE_CORE_GRAPH: BlueprintGraph = ${literal(templates.moge.core)};

export const MOGE_APPENDED_GRAPH: BlueprintGraph = ${literal(templates.moge.appended)};

export const SAM3_CORE_GRAPH: BlueprintGraph = ${literal(templates.sam3.core)};

export const SAM3_APPENDED_GRAPH: BlueprintGraph = ${literal(templates.sam3.appended)};

/** The runtime submit shape: the same nodes without the editor-only _meta. */
export function asApiGraph(graph: BlueprintGraph): ApiGraph {
  return graph;
}
`;

mkdirSync(OUT_DIR, {recursive: true});
writeFileSync(join(OUT_DIR, "graph-templates.ts"), source);
console.log("wrote generated/graph-templates.ts", source.length, "bytes");
for (const [kind, graph] of Object.entries(templates)) {
  console.log(kind, "core nodes:", Object.keys(graph.core).sort().join(", "));
  console.log(kind, "appended nodes:", Object.keys(graph.appended).join(", "));
}
