CREATE TABLE pose_previews (
 id uuid PRIMARY KEY,
 workspace_id uuid NOT NULL REFERENCES workspaces(id),
 project_id uuid NOT NULL,
 source_asset_id uuid NOT NULL,
 source_sha256 text NOT NULL,
 worker_id uuid NOT NULL,
 created_by uuid NOT NULL REFERENCES users(id),
 request_hash text NOT NULL,
 state text NOT NULL CHECK(state IN ('pending','preparing','prepared','queued','succeeded','failed','cancel_requested','canceled')),
 normalized_receipt jsonb,
 run_id uuid,
 lease_owner uuid,
 lease_expires_at timestamptz,
 error text,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(workspace_id,id),
 FOREIGN KEY(workspace_id,project_id) REFERENCES projects(workspace_id,id),
 FOREIGN KEY(workspace_id,source_asset_id) REFERENCES assets(workspace_id,id),
 FOREIGN KEY(workspace_id,worker_id) REFERENCES workers(workspace_id,id),
 FOREIGN KEY(workspace_id,run_id) REFERENCES runs(workspace_id,id)
);
CREATE TABLE pose_preview_frames (
 workspace_id uuid NOT NULL,
 preview_id uuid NOT NULL,
 ordinal integer NOT NULL CHECK(ordinal BETWEEN 0 AND 5),
 planned_asset_id uuid NOT NULL,
 asset_id uuid,
 storage_key text NOT NULL,
 sha256 text NOT NULL,
 bytes bigint NOT NULL CHECK(bytes>0 AND bytes<=16777216),
 frame_index integer NOT NULL CHECK(frame_index BETWEEN 0 AND 640),
 seconds double precision NOT NULL CHECK(seconds>=0 AND seconds<=27),
 width integer NOT NULL CHECK(width BETWEEN 1 AND 1920),
 height integer NOT NULL CHECK(height BETWEEN 1 AND 1920),
 PRIMARY KEY(workspace_id,preview_id,ordinal),
 UNIQUE(workspace_id,planned_asset_id),
 UNIQUE(workspace_id,asset_id),
 FOREIGN KEY(workspace_id,preview_id) REFERENCES pose_previews(workspace_id,id),
 FOREIGN KEY(workspace_id,asset_id) REFERENCES assets(workspace_id,id)
);
